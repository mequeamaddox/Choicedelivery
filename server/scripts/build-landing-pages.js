// Writes the area and service pages (landing/<slug>.html) and landing/sitemap.xml from
// landing/local-pages.js. Run `npm run build:landing-pages`, then `npm run build:landing-css`.
const fs = require('fs');
const path = require('path');
const { AREAS, SERVICES, ALL } = require('../landing/local-pages');

const DIR = path.join(__dirname, '..', 'landing');
const SITE = 'https://choicedeliverysc.com';
const today = new Date().toISOString().slice(0, 10);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const linkList = (pages, current) => pages.map((p) => (p.slug === current
  ? `<li class="font-semibold text-white">${esc(p.nav)}</li>`
  : `<li><a href="/${p.slug}" class="hover:text-white">${esc(p.nav)}</a></li>`)).join('\n                        ');

function page(p) {
  const isArea = AREAS.includes(p);
  const schema = [
    {
      '@context': 'https://schema.org',
      '@type': 'Service',
      name: p.title,
      serviceType: 'Courier service',
      description: p.description,
      url: `${SITE}/${p.slug}`,
      provider: { '@id': `${SITE}/#business` },
      areaServed: isArea ? p.nav.split(' & ').map((name) => ({ '@type': 'Place', name: `${name}, SC` }))
        : [{ '@type': 'City', name: 'Columbia, SC' }, { '@type': 'State', name: 'South Carolina' }],
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: `${SITE}/` },
        { '@type': 'ListItem', position: 2, name: p.nav, item: `${SITE}/${p.slug}` },
      ],
    },
  ];
  return `<!DOCTYPE html>
<!-- Generated by scripts/build-landing-pages.js from landing/local-pages.js; edit those, not this file. -->
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${esc(p.title)} | Choice Delivery SC</title>
    <meta name="description" content="${esc(p.description)}">
    <link rel="canonical" href="${SITE}/${p.slug}">
    <meta name="theme-color" content="#0f766e">
    <meta property="og:type" content="website">
    <meta property="og:site_name" content="Choice Delivery SC">
    <meta property="og:title" content="${esc(p.title)}">
    <meta property="og:description" content="${esc(p.description)}">
    <meta property="og:image" content="${SITE}/logo.png">
    <meta property="og:url" content="${SITE}/${p.slug}">
    <script type="application/ld+json">${JSON.stringify(schema)}</script>
    <link rel="icon" type="image/png" href="favicon.png">
    <link rel="stylesheet" href="/site.css?v=6">
    <style>
        :root { --choice-teal: #0f766e; --choice-mint: #5eead4; --choice-mint-light: #a7f3d0; }
        .bg-choice-teal { background-color: var(--choice-teal); }
        .bg-choice-mint { background-color: var(--choice-mint); }
        .text-choice-teal { color: var(--choice-teal); }
        .text-choice-mint-light { color: var(--choice-mint-light); }
        .gradient-bg { background: linear-gradient(135deg, var(--choice-mint) 0%, var(--choice-teal) 100%); }
    </style>
</head>
<body class="text-gray-800 bg-white">
    <nav class="bg-white shadow">
        <div class="max-w-6xl mx-auto px-4 flex justify-between items-center py-3 gap-4">
            <a href="/"><img src="logo.png" alt="Choice Delivery SC" class="h-12 w-auto"></a>
            <div class="flex items-center gap-4">
                <a href="/#quote" class="bg-choice-teal text-white px-4 py-2 rounded-lg font-semibold hover:bg-opacity-90">Get a quote</a>
            </div>
        </div>
    </nav>

    <header class="gradient-bg text-white py-14">
        <div class="max-w-4xl mx-auto px-4">
            <p class="text-sm"><a href="/" class="underline hover:opacity-80">Home</a> &rsaquo; ${esc(p.nav)}</p>
            <h1 class="text-4xl md:text-5xl font-bold mt-3">${esc(p.h1)}</h1>
            <p class="text-xl mt-5 max-w-3xl">${esc(p.intro)}</p>
            <div class="flex flex-col sm:flex-row gap-3 mt-8">
                <a href="/#quote" class="bg-white text-choice-teal px-6 py-3 rounded-lg text-lg font-semibold text-center hover:bg-gray-100">Get your instant price</a>
                <a href="/#contact" class="border-2 border-white text-white px-6 py-3 rounded-lg text-lg font-semibold text-center hover:bg-white hover:text-choice-teal">Send us a message</a>
            </div>
        </div>
    </header>

    <main class="max-w-4xl mx-auto px-4 py-12 space-y-10">
${p.sections.map(([h, t]) => `        <section>
            <h2 class="text-2xl font-bold text-choice-teal mb-3">${esc(h)}</h2>
            <p class="text-lg text-gray-700 leading-relaxed">${esc(t)}</p>
        </section>`).join('\n')}
        <section>
            <h2 class="text-2xl font-bold text-choice-teal mb-4">How it works</h2>
            <ol class="grid md:grid-cols-3 gap-4">
                <li class="bg-gray-50 rounded-xl p-5"><p class="font-bold text-lg">1. Get your price</p><p class="text-gray-600 mt-1">Enter the pickup and delivery addresses for an instant quote. No calling around.</p></li>
                <li class="bg-gray-50 rounded-xl p-5"><p class="font-bold text-lg">2. Book in minutes</p><p class="text-gray-600 mt-1">Choose standard or Rush and a car, minivan or pickup truck, then pay securely online.</p></li>
                <li class="bg-gray-50 rounded-xl p-5"><p class="font-bold text-lg">3. Track it live</p><p class="text-gray-600 mt-1">Follow the driver on the map. Delivery is confirmed with a photo, signature and GPS location.</p></li>
            </ol>
        </section>
        <section>
            <h2 class="text-2xl font-bold text-choice-teal mb-4">Questions</h2>
            <div class="space-y-5">
${p.faqs.map(([q, a]) => `                <div><h3 class="font-semibold text-lg">${esc(q)}</h3><p class="text-gray-700 mt-1">${esc(a)}</p></div>`).join('\n')}
            </div>
            <p class="mt-6"><a href="/#faq" class="text-choice-teal font-semibold hover:underline">More questions and answers &rarr;</a></p>
        </section>
        <section class="bg-choice-teal text-white rounded-xl p-8 text-center">
            <h2 class="text-3xl font-bold">Need it there today?</h2>
            <p class="text-lg mt-2">Open 8 AM &ndash; 10 PM, 7 days a week.</p>
            <div class="flex flex-col sm:flex-row gap-3 justify-center mt-6">
                <a href="/#quote" class="bg-white text-choice-teal px-6 py-3 rounded-lg text-lg font-semibold hover:bg-gray-100">Get your instant price</a>
                <a href="/#contact" class="border-2 border-white px-6 py-3 rounded-lg text-lg font-semibold hover:bg-white hover:text-choice-teal">Send us a message</a>
            </div>
        </section>
    </main>

    <footer class="bg-gray-900 text-white py-10">
        <div class="max-w-6xl mx-auto px-4 grid sm:grid-cols-3 gap-8">
            <div>
                <h2 class="text-lg font-semibold mb-3">Areas we serve</h2>
                <ul class="space-y-2 text-choice-mint-light">
                        <li><a href="/" class="hover:text-white">Columbia</a></li>
                        ${linkList(AREAS, p.slug)}
                </ul>
            </div>
            <div>
                <h2 class="text-lg font-semibold mb-3">Services</h2>
                <ul class="space-y-2 text-choice-mint-light">
                        ${linkList(SERVICES, p.slug)}
                </ul>
            </div>
            <div>
                <h2 class="text-lg font-semibold mb-3">Choice Delivery SC</h2>
                <div class="space-y-2 text-choice-mint-light">
                    <p><a href="tel:8039497034" class="hover:text-white">(803) 949-7034</a></p>
                    <p><a href="mailto:info@choicedeliverysc.com" class="hover:text-white">info@choicedeliverysc.com</a></p>
                    <p>Columbia, SC &middot; 8 AM &ndash; 10 PM daily</p>
                    <p><a href="/terms" class="hover:text-white">Terms</a> &middot; <a href="/privacy" class="hover:text-white">Privacy</a></p>
                </div>
            </div>
        </div>
    </footer>
    <script src="/attribution.js?v=1"></script>
</body>
</html>
`;
}

for (const p of ALL) fs.writeFileSync(path.join(DIR, `${p.slug}.html`), page(p));

const urls = [['', '1.0'], ...ALL.map((p) => [p.slug, '0.8']), ['terms', '0.3'], ['privacy', '0.3']];
fs.writeFileSync(path.join(DIR, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(([u, pr]) => `  <url><loc>${SITE}/${u}</loc><lastmod>${today}</lastmod><priority>${pr}</priority></url>`).join('\n')}
</urlset>
`);
console.log(`Wrote ${ALL.length} pages and sitemap.xml`);
